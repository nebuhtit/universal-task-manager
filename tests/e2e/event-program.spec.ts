import { expect, test, type Locator } from '@playwright/test';

const openDates = async (editor: Locator) => {
  await editor.locator('[data-editor-section="dates"]').evaluate((element) => { (element as HTMLDetailsElement).open = true; });
};

test('program start preserves duration and invalid end has a visible dismissible warning outside scrolling content', async ({ page }, testInfo) => {
  const activate = async (control: Locator) => { if (testInfo.project.use.hasTouch) await control.tap(); else await control.click(); };
  await page.goto('/');
  await page.getByLabel('Workspace name').fill('Program warning');
  await page.getByLabel('Password', { exact: true }).fill('program-test-password');
  await page.getByLabel('Confirm password').fill('program-test-password');
  await activate(page.getByRole('button', { name: 'Create encrypted workspace' }));
  await page.getByPlaceholder('Add new item').fill('Program warning item');
  await page.getByPlaceholder('Add new item').press('Enter');
  const editor = page.getByRole('dialog', { name: 'Item editor', exact: true });
  await openDates(editor);
  await editor.getByLabel('Event opens', { exact: true }).fill('2030-09-21T21:09');
  await editor.getByLabel('Event ends', { exact: true }).fill('2030-09-21T23:00');
  const program = editor.locator('.event-program');
  await activate(program.locator(':scope > summary'));
  await activate(program.getByRole('button', { name: 'Add block', exact: true }));
  await program.getByLabel('Block title 1', { exact: true }).fill('Go');
  await program.getByLabel('Block start 1', { exact: true }).fill('21:50');
  await expect(program.getByLabel('Block end 1', { exact: true })).toHaveValue('22:20');
  await expect(program.getByRole('button', { name: '+1 day', exact: true })).toHaveCount(0);
  await program.getByLabel('Block end 1', { exact: true }).fill('21:09');
  await expect(program.getByLabel('Block end 1', { exact: true })).toHaveValue('22:20');
  const warning = editor.locator('.warning-notice-stack').getByRole('alert');
  await expect(warning).toContainText('Block 1');
  await expect(warning).toContainText('previous end was retained');
  for (const colorScheme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme });
    await editor.locator('.ui-dialog-content').evaluate(element => { element.scrollTop = element.scrollHeight; });
    await expect(warning).toBeVisible();
    const box = await warning.boundingBox();
    expect(box!.y).toBeGreaterThanOrEqual(0);
    expect(box!.y + box!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
  }
  await activate(warning.getByRole('button', { name: 'Dismiss warning' }));
  await expect(warning).toHaveCount(0);
  await program.getByLabel('Block end 1', { exact: true }).fill('21:50');
  await expect(program.getByLabel('Block end 1', { exact: true })).toHaveValue('22:20');
  const dismiss = editor.getByRole('button', { name: 'Dismiss warning' });
  await dismiss.focus();
  await page.keyboard.press('Enter');
  await expect(editor.locator('.warning-notice-stack').getByRole('alert')).toHaveCount(0);
  await activate(editor.getByRole('button', { name: 'Save item', exact: true }));
  await expect(editor).toBeHidden();
});

test('infers missing event boundaries and generates the script on Save without Apply', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Workspace name').fill('Automatic program');
  await page.getByLabel('Password', { exact: true }).fill('program-test-password');
  await page.getByLabel('Confirm password').fill('program-test-password');
  await page.getByRole('button', { name: 'Create encrypted workspace' }).click();
  await page.getByPlaceholder('Add new item').fill('New program');
  await page.getByPlaceholder('Add new item').press('Enter');
  const editor = page.getByRole('dialog', { name: 'Item editor', exact: true });
  const program = editor.locator('.event-program');
  await openDates(editor);
  await program.locator(':scope > summary').click();
  await program.getByRole('button', { name: 'Add block', exact: true }).click();
  await program.getByLabel('Block title 1', { exact: true }).fill('First');
  await program.getByLabel('Block start 1', { exact: true }).fill('17:00');
  await program.getByLabel('Block end 1', { exact: true }).fill('17:45');
  await program.getByRole('button', { name: 'Add block', exact: true }).click();
  await program.getByLabel('Block title 2', { exact: true }).fill('Second');
  await expect(program.getByLabel('Block start 2', { exact: true })).toHaveValue('17:45');
  await expect(editor.getByLabel('Event opens', { exact: true })).toHaveValue(/T17:00$/);
  await expect(editor.getByLabel('Event ends', { exact: true })).toHaveValue(/T18:15$/);
  await editor.getByRole('button', { name: 'Save item', exact: true }).click();
  await expect(editor).toBeHidden();
  await page.getByText('New program', { exact: true }).first().click();
  await expect(editor.locator('.item-script-row')).toHaveCount(1);
  await openDates(editor);
  await program.locator(':scope > summary').click();
  await program.getByLabel('Block title 1', { exact: true }).fill('Discarded edit');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByText('New program', { exact: true }).first().click();
  await openDates(editor);
  await program.locator(':scope > summary').click();
  await expect(program.getByLabel('Block title 1', { exact: true })).toHaveValue('First');
});

test('program edits, shifts, trims with confirmation and saves one managed script', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Workspace name').fill('Program checks');
  await page.getByLabel('Password', { exact: true }).fill('program-test-password');
  await page.getByLabel('Confirm password').fill('program-test-password');
  await page.getByRole('button', { name: 'Create encrypted workspace' }).click();
  await page.getByPlaceholder('Add new item').fill('Program workshop');
  await page.getByPlaceholder('Add new item').press('Enter');
  const editor = page.getByRole('dialog', { name: 'Item editor', exact: true });
  await openDates(editor);
  await editor.getByLabel('Event opens', { exact: true }).fill('2030-09-21T17:00');
  await editor.getByLabel('Event ends', { exact: true }).fill('2030-09-21T21:00');
  const program = editor.locator('.event-program');
  await openDates(editor);
  await program.locator(':scope > summary').click();
  await program.getByRole('button', { name: 'Add block', exact: true }).click();
  await program.getByLabel('Block title 1', { exact: true }).fill('Lesson');
  await program.getByLabel('Block end 1', { exact: true }).fill('17:45');
  await program.getByRole('button', { name: 'Add block', exact: true }).click();
  await program.getByLabel('Block title 2', { exact: true }).fill('Tea');
  await program.getByLabel('Block start 2', { exact: true }).fill('18:15');
  await program.getByLabel('Block end 2', { exact: true }).fill('21:00');
  await program.getByRole('button', { name: 'Apply', exact: true }).click();
  await editor.getByLabel('Event opens', { exact: true }).fill('2030-09-22T18:00');
  await expect(program.getByLabel('Block start 1', { exact: true })).toHaveValue('18:00');
  await expect(editor.getByLabel('Event ends', { exact: true })).toHaveValue('2030-09-22T22:00');
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('Tea'); await dialog.dismiss(); });
  await editor.getByLabel('Event ends', { exact: true }).fill('2030-09-22T18:30');
  await expect(editor.getByLabel('Event ends', { exact: true })).toHaveValue('2030-09-22T22:00');
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('delete'); await dialog.accept(); });
  await editor.getByLabel('Event ends', { exact: true }).fill('2030-09-22T18:30');
  await expect(program.locator('.program-block')).toHaveCount(1);
  await expect(program.getByLabel('Block end 1', { exact: true })).toHaveValue('18:30');
  const travel = editor.locator('.travel-time-disclosure').first();
  await travel.locator(':scope > summary').click();
  await expect(travel.getByLabel('Travel time amount')).toHaveValue('');
  await travel.getByLabel('Travel time amount').fill('45 min');
  await program.getByLabel('Block title 1', { exact: true }).focus();
  await expect(travel.getByLabel('Travel time amount')).toHaveValue('45 min');
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme });
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme);
    const addButton = program.getByRole('button', { name: 'Add block', exact: true });
    await expect(addButton).toBeEnabled();
    await expect(addButton).toHaveCSS('background-color', theme === 'dark' ? 'rgb(0, 0, 0)' : 'rgb(255, 255, 255)');
    await expect(addButton).toHaveCSS('color', theme === 'dark' ? 'rgb(241, 241, 241)' : 'rgb(13, 13, 13)');
    await program.scrollIntoViewIfNeeded();
    expect(await editor.evaluate((node) => node.scrollWidth <= node.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`program-${theme}.png`) });
  }
  await program.getByLabel('Block end 1', { exact: true }).fill('19:00');
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('Extend the event'); await dialog.accept(); });
  await editor.getByRole('button', { name: 'Save item', exact: true }).click();
  await expect(editor).toBeHidden();
  await page.locator('.item-card').filter({ hasText: 'Program workshop' }).first().locator('.item-main').click();
  await openDates(editor);
  await expect(editor.getByLabel('Event ends', { exact: true })).toHaveValue('2030-09-22T19:00');
  await program.locator(':scope > summary').click();
  await expect(program.locator('.program-block')).toHaveCount(1);
  await program.getByRole('button', { name: 'Apply', exact: true }).click();
  await editor.locator('[data-editor-section="more"] > summary').click();
  const scripts = editor.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Scripts/ }) }).last();
  await scripts.locator(':scope > summary').click();
  await expect(scripts.locator('.item-script-row')).toHaveCount(1);
  await expect(scripts.getByText('Automatically managed · Event program')).toBeVisible();
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(editor).toBeHidden();
});
